// Production-build, disposable data only. Checks service-worker cold starts too.
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const fixture = await mkdtemp(path.join(tmpdir(), 'scriptorium-offline-'));
const origin = 'http://127.0.0.1:5191';
const server = spawn(process.execPath, ['build'], { env: { ...process.env, DATA_ROOT: fixture, HOST: '127.0.0.1', PORT: '5191', ORIGIN: origin }, stdio: ['ignore', 'pipe', 'pipe'] });
let log = '', browser, page; const errors = []; const checks = [];
server.stdout.on('data', c => log += c); server.stderr.on('data', c => log += c);
const check = s => { checks.push(s); console.log('PASS', s); };
try {
 for (let n = 0; n < 100; n++) { try { if ((await fetch(origin)).ok) break; } catch {} await new Promise(r => setTimeout(r, 100)); }
 browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
 const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
 const api = async (route, method = 'GET', data) => { const r = await context.request.fetch(origin + route, { method, data, headers: { Origin: origin } }); assert(r.ok(), `${route} ${r.status()}`); return r.json(); };
 const credentials = { username: 'offline-fixture', password: 'disposable-offline-password' };
 await api('/api/auth/setup', 'POST', credentials); await api('/api/auth/login', 'POST', credentials);
 const work = await api('/api/novels', 'POST', { title: 'Offline fixture' });
 const create = data => api(`/api/novels/${work.id}/tree/nodes`, 'POST', data);
 const folder = await create({ type: 'folder', title: 'Part one', sort_order: 1 });
 const folder2 = await create({ type: 'folder', title: 'Part two', sort_order: 2 });
 const a = await create({ type: 'document', title: 'First chapter', parent_id: folder.id, sort_order: 1 });
 const ep = await create({ type: 'document', title: 'Epigraph', parent_id: folder.id, sort_order: 2 });
 const b = await create({ type: 'document', title: 'Second chapter', parent_id: folder.id, sort_order: 3 });
 const c = await create({ type: 'document', title: 'New part', parent_id: folder2.id, sort_order: 1 });
 for (const doc of [a, ep, b, c]) await api(`/api/documents/${doc.id}`, 'PUT', { content: `<p>Original ${doc.title} writing.</p>` });
 await api(`/api/novels/${work.id}/tree/nodes/${ep.id}`, 'PATCH', { numbering_include: false });
 page = await context.newPage();
 page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
 await page.goto(`${origin}/novels/${work.id}`);
 await page.evaluate(() => navigator.serviceWorker.ready);
 await page.reload();
 await page.getByRole('button', { name: 'Number chapters: off' }).click();
 await page.getByRole('button', { name: 'Keep on this device' }).click();
 await page.getByRole('button', { name: 'Refresh device copy' }).waitFor();
 check('complete work downloaded and offline application installed');
 await page.getByRole('button', { name: 'First chapter', exact: false }).click();
 await page.locator('.ProseMirror').waitFor();
 await page.getByRole('button', { name: 'Next chapter', exact: true }).click();
 await page.waitForFunction(() => document.querySelector('.editor-header .doc-title')?.textContent === 'Epigraph');
 assert.equal(await page.locator('.editor-header .chapter-number').count(), 0);
 await page.getByRole('button', { name: 'Next chapter', exact: true }).click();
 await page.getByText('Chapter 2', { exact: true }).waitFor();
 check('reader navigation includes epigraph while numbering skips it');
 await page.getByRole('button', { name: 'Next chapter', exact: true }).click();
 await page.getByText('Chapter 1', { exact: true }).waitFor();
 check('numbering restarts in the next folder');
 await page.getByRole('button', { name: 'Open binder' }).click();
 const row = page.getByRole('treeitem').filter({ has: page.getByRole('button', { name: 'Second chapter', exact: false }) });
 await row.getByRole('button', { name: 'Move document' }).click();
 await Promise.all([page.waitForResponse(r => r.url().endsWith(`/api/novels/${work.id}/tree`) && r.request().method() === 'GET'), row.getByRole('button', { name: 'Move up', exact: false }).click()]);
 await page.getByText('Loading chapters…', {exact:true}).waitFor({state:'hidden'});
 const moved = await api(`/api/documents/${b.id}`);
 assert(moved.sort_order < (await api(`/api/documents/${ep.id}`)).sort_order);
 check('mobile move-up reorders chapters');
 await row.getByRole('button', { name: 'Move document' }).click();
 await row.getByRole('button', { name: 'Move into…', exact: false }).click();
 await page.getByRole('dialog').getByRole('button', { name: 'Part two', exact: true }).click();
 assert.equal((await api(`/api/documents/${b.id}`)).parent_id, folder2.id);
 check('mobile chapter move between folders persists');
 await page.getByRole('button', { name: 'Compile', exact: true }).click();
 await page.getByLabel('Output format').selectOption('pdf');
 const downloadPromise = page.waitForEvent('download');
 await page.getByRole('button', { name: 'Export', exact: true }).click();
 const exported = await downloadPromise;
 await exported.saveAs(path.join(fixture, 'mobile-export.pdf'));
 assert.equal((await readFile(path.join(fixture, 'mobile-export.pdf'))).subarray(0,5).toString(), '%PDF-');
 check('mobile PDF export produces a downloaded PDF');
 await page.getByRole('button', { name: 'Cancel', exact: true }).click();
 await page.getByRole('button', { name: 'Refresh device copy' }).click();
 await page.getByRole('button', { name: 'Refresh device copy' }).waitFor();
 await context.setOffline(true);
 await page.goto(`${origin}/offline`);
 await page.getByLabel('Work', { exact: true }).selectOption(work.id);
 await page.locator('.ProseMirror').waitFor();
 await page.getByRole('button', { name: 'Edit', exact: true }).click();
 await page.locator('.ProseMirror').fill('Writing from the phone while the server is unavailable.');
 await page.getByText('Saved on this device', { exact: true }).waitFor();
 await page.reload();
 await page.getByLabel('Work', { exact: true }).selectOption(work.id);
 await page.locator('.ProseMirror').waitFor();
 assert.match(await page.locator('.ProseMirror').innerText(), /Writing from the phone/);
 check('offline edit survives a full offline reload');
 await page.screenshot({ path: path.join(fixture, 'offline-phone.png') });
 await context.setOffline(false);
 await page.getByText('All device changes are synced to the server.', { exact: true }).waitFor();
 assert.match((await api(`/api/documents/${a.id}`)).content, /Writing from the phone/);
 check('reconnection syncs device writing');
 await context.setOffline(true);
 await page.locator('.ProseMirror').fill('A conflicting phone version that must never be lost.');
 await page.getByText('Saved on this device', { exact: true }).waitFor();
 // APIRequestContext uses its own networking; this simulates a second device.
 await api(`/api/documents/${a.id}`, 'PUT', { content: '<p>Independent second-device writing.</p>' });
 await context.setOffline(false);
 await page.getByText(/Conflict: the server has a different version/).waitFor();
 assert.match((await api(`/api/documents/${a.id}`)).content, /Independent second-device/);
 assert.match(await page.locator('.ProseMirror').innerText(), /conflicting phone version/);
 await page.reload(); await page.getByLabel('Work', { exact: true }).selectOption(work.id);
 await page.locator('.ProseMirror').waitFor();
 assert.match(await page.locator('.ProseMirror').innerText(), /conflicting phone version/);
 check('cross-device conflict preserves both versions, including after reload');
 // Two tabs cannot silently replace one another's unsynced draft.
 const other = await context.newPage();
 await other.goto(`${origin}/offline`);
 await other.getByLabel('Work', { exact: true }).selectOption(work.id);
 await other.locator('.ProseMirror').waitFor();
 await context.setOffline(true);
 await page.locator('.ProseMirror').fill('First tab writing must be retained.');
 await page.getByText('Saved on this device', { exact: true }).waitFor();
 await other.locator('.ProseMirror').fill('Second tab conflicting writing stays in its editor.');
 await other.getByText(/Could not save on this device/).first().waitFor();
 await other.close();
 await page.reload(); await page.getByLabel('Work', { exact: true }).selectOption(work.id);
 await page.locator('.ProseMirror').waitFor();
 assert.match(await page.locator('.ProseMirror').innerText(), /First tab writing/);
 check('two-tab conflict cannot overwrite the durable draft');
 await page.evaluate(() => { IDBObjectStore.prototype.put = function() { throw new DOMException('Fixture quota', 'QuotaExceededError'); }; });
 await page.locator('.ProseMirror').fill('Quota failure writing remains available to download.');
 await page.getByText(/Could not save on this device|Fixture quota/).first().waitFor();
 await page.getByRole('button', { name: 'Download a copy', exact: true }).waitFor();
 check('storage failure keeps unsaved text and offers a recovery download');
 const desktop = await browser.newContext({ viewport: {width:1280,height:900} });
 await desktop.request.post(origin+'/api/auth/login',{data:credentials,headers:{Origin:origin}});
 const desktopPage = await desktop.newPage();
 await desktopPage.goto(`${origin}/novels/${work.id}`);
 const sourceRow = desktopPage.getByRole('treeitem').filter({has:desktopPage.getByRole('button',{name:'First chapter',exact:false})});
 const targetRow = desktopPage.getByRole('treeitem').filter({has:desktopPage.getByText('Part two',{exact:true})});
 await Promise.all([desktopPage.waitForResponse(r=>r.url().endsWith(`/api/novels/${work.id}/tree`) && r.request().method()==='GET'),sourceRow.dragTo(targetRow)]);
 assert.equal((await api(`/api/documents/${a.id}`)).parent_id,folder2.id);
 check('desktop drag moves a chapter into another folder');
 await targetRow.hover();
 await targetRow.getByRole('button',{name:'Move folder'}).click();
 await targetRow.getByRole('button',{name:'Disable folder numbering'}).click();
 await desktopPage.getByRole('button',{name:'First chapter',exact:true}).click();
 assert.equal(await desktopPage.locator('.editor-header .chapter-number').count(),0);
 check('folder opt-out removes automatic numbers');
 await desktop.close();
 assert.deepEqual(errors, []);
 await writeFile(path.join(fixture, 'result.json'), JSON.stringify({ passed: true, checks }, null, 2));
 console.log('Artifacts:', fixture);
} catch (e) { await writeFile(path.join(fixture, 'server.log'), log); console.error('Artifacts:', fixture, 'Browser errors:', errors); if (page) { await page.screenshot({ path: path.join(fixture, 'failure.png') }); console.error((await page.locator('body').innerText()).slice(0,2000)); } throw e; }
finally { await browser?.close(); server.kill('SIGTERM'); }
